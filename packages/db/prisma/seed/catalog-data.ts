type AttrType = 'TEXT' | 'NUMBER' | 'BOOLEAN' | 'ENUM' | 'MULTI_ENUM';
export interface AttributeSeed {
  key: string;
  label: string;
  type: AttrType;
  unit?: string;
  options?: Array<{ value: string; label: string }>;
  isFilterable?: boolean;
}

const opts = (...pairs: Array<[string, string]>) =>
  pairs.map(([value, label]) => ({ value, label }));
const same = (...values: string[]) => values.map((v) => ({ value: v, label: v }));
const yesNo = (key: string, label: string): AttributeSeed => ({
  key,
  label,
  type: 'BOOLEAN',
  isFilterable: true,
});

